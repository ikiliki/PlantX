function at(region: string, lat: number, lng: number) {
  const area = resolveArea(region)
  if (!area) throw new Error(`Unknown plant region: ${region}`)
  return {
    locationZone: area.region,
    locationZoneHe: area.regionHe,
    lat,
    lng,
  }
}

